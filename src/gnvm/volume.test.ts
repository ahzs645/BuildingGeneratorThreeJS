function apiWith(values: Record<string, SockVal>): EvalAPI {
  const input = (name: string) => values[name];
  const field = (name: string) => {
    const value = input(name);
    return value instanceof Field ? value : Field.of(typeof value === "number" ? value : 0);
  };
  return {
    node: { name: "volume-test", type: "volume-test", label: null, inputs: [], outputs: [] },
    input,
    inputs: (name) => values[name] === undefined ? [] : [values[name]],
    geoInputs: (name) => values[name] instanceof Geometry ? [values[name] as Geometry] : [],
    geo: (name) => values[name] instanceof Geometry ? values[name] as Geometry : new Geometry(),
    field,
    num: (name) => {
      const value = input(name);
      return value instanceof Field ? asNum(value.value) : typeof value === "number" ? value : 0;
    },
    vec: (name) => {
      const value = input(name);
      return value instanceof Field ? asVec3(value.value) : [0, 0, 0];
    },
    bool: (name) => Boolean(asNum(field(name).value)),
    str: (name) => String(input(name) ?? ""),
    ref: () => null,
    prop: (_name, fallback) => fallback as never,
    resolve: (value, geometry, domain) => value.array(makeFieldCtx(geometry, domain)),
  };
}

function gridValueAt(
  grid: ReturnType<typeof meshToSdfGridForTest>,
  point: Vec3,
): number {
  const coordinate = point.map((value, axis) =>
    Math.round((value - grid.origin[axis]) / grid.voxelSize[axis])) as Vec3;
  return grid.values[
    coordinate[2] * grid.resolution[0] * grid.resolution[1]
      + coordinate[1] * grid.resolution[0]
      + coordinate[0]
  ];
}

