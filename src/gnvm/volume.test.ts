test("medium adaptive grids take the bounded batch-reduction path", () => {
  const side = 40;
  const resolution: Vec3 = [side, side, side];
  const values = new Float32Array(side ** 3);
  for (let z = 0; z < side; z++)
    for (let y = 0; y < side; y++)
      for (let x = 0; x < side; x++)
        values[z * side * side + y * side + x] =
          Math.hypot(x - 19.5, y - 19.5, z - 19.5) - 14;
  const full = surfaceNetsForTest(values, resolution, 0, [0, 0, 0], [1, 1, 1]);
  assert.ok(full.positions.length > MAX_TOPOLOGY_ADAPTIVE_VERTICES);

  const started = performance.now();
  const adaptive = adaptiveSurfaceNetsForTest(
    values,
    resolution,
    0,
    [0, 0, 0],
    [1, 1, 1],
    .5,
  );
  const elapsed = performance.now() - started;
  assert.ok(adaptive.positions.length < full.positions.length);
  const edgeUses = new Map<string, number>();
  for (const face of adaptive.faces) for (let corner = 0; corner < face.length; corner++) {
    const a = face[corner], b = face[(corner + 1) % face.length];
    const key = a < b ? `${a},${b}` : `${b},${a}`;
    edgeUses.set(key, (edgeUses.get(key) ?? 0) + 1);
  }
  assert.ok([...edgeUses.values()].every((uses) => uses === 2));
  // This is deliberately generous for CI; it catches accidentally routing
  // medium grids through thousands of one-at-a-time edge rebuilds and sorts.
  assert.ok(elapsed < 2_000, `bounded adaptive extraction took ${elapsed.toFixed(1)} ms`);
});

