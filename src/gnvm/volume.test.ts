test("Volume Cube to Mesh matches Blender across Grid, Size, Amount, and nonzero isovalues", () => {
  const volumeCube = REGISTRY.get("GeometryNodeVolumeCube");
  const volumeToMesh = REGISTRY.get("GeometryNodeVolumeToMesh");
  assert.ok(volumeCube && volumeToMesh);
  const cubeFixture = volumeToMeshBlenderFixture.volume_cube;
  assert.equal(volumeToMeshBlenderFixture.blender, "5.1.2");
  assert.equal(
    volumeToMeshBlenderFixture.generator,
    "tools/blender_volume_to_mesh_topology_probe.py",
  );

  const density = Field.perElem((index, context) => {
    const point = context.position?.(index) ?? [0, 0, 0];
    return Math.hypot(point[0], point[1], point[2]) - cubeFixture.radius;
  });
  const previousCubeCount = APPROXIMATIONS.get("GeometryNodeVolumeCube") ?? 0;
  const previousMeshCount = APPROXIMATIONS.get("GeometryNodeVolumeToMesh") ?? 0;
  const volume = volumeCube(apiWith({
    Density: density,
    Background: Field.of(cubeFixture.background),
    Min: Field.of(cubeFixture.min),
    Max: Field.of(cubeFixture.max),
    "Resolution X": Field.of(cubeFixture.resolution[0]),
    "Resolution Y": Field.of(cubeFixture.resolution[1]),
    "Resolution Z": Field.of(cubeFixture.resolution[2]),
  })).Volume;
  assert.ok(volume && typeof volume === "object" && volume.kind === "GNVM_VOLUME_GRID");

  for (const caseName of ["grid_zero", "grid_nonzero", "size_zero", "amount_zero"]) {
    const fixture = volumeToMeshBlenderFixture.cases[caseName];
    const result = volumeToMesh(apiWith({
      Volume: volume,
      "Resolution Mode": fixture.inputs.resolution_mode,
      "Voxel Size": Field.of(fixture.inputs.voxel_size),
      "Voxel Amount": Field.of(fixture.inputs.voxel_amount),
      Threshold: Field.of(fixture.inputs.threshold),
      Adaptivity: Field.of(fixture.inputs.adaptivity),
    })).Mesh;
    assert.ok(result instanceof Geometry && result.mesh, caseName);
    const mesh = result.mesh;
    const edges = new Set<string>();
    for (const face of mesh.faces) for (let corner = 0; corner < face.length; corner++) {
      const a = face[corner], b = face[(corner + 1) % face.length];
      edges.add(a < b ? `${a},${b}` : `${b},${a}`);
    }
    const faceSizes = Object.fromEntries([...new Set(mesh.faces.map((face) => face.length))]
      .sort((a, b) => a - b)
      .map((size) => [String(size), mesh.faces.filter((face) => face.length === size).length]));
    let signedVolume = 0;
    for (const face of mesh.faces) for (let corner = 1; corner < face.length - 1; corner++) {
      const a = mesh.positions[face[0]];
      const b = mesh.positions[face[corner]];
      const c = mesh.positions[face[corner + 1]];
      signedVolume += (
        a[0] * (b[1] * c[2] - b[2] * c[1])
        + a[1] * (b[2] * c[0] - b[0] * c[2])
        + a[2] * (b[0] * c[1] - b[1] * c[0])
      ) / 6;
    }
    const bounds = (kind: "min" | "max") => [0, 1, 2].map((axis) =>
      Math[kind](...mesh.positions.map((point) => point[axis]))) as Vec3;
    const moments = {
      abs: [0, 1, 2].map((axis) => mesh.positions.reduce((sum, point) => sum + Math.abs(point[axis]), 0)) as Vec3,
      squared: [0, 1, 2].map((axis) => mesh.positions.reduce((sum, point) => sum + point[axis] ** 2, 0)) as Vec3,
    };
    assert.equal(mesh.positions.length, fixture.vertices, `${caseName} vertices`);
    assert.equal(edges.size, fixture.edges, `${caseName} edges`);
    assert.equal(mesh.faces.length, fixture.faces, `${caseName} faces`);
    assert.deepEqual(faceSizes, fixture.face_sizes, `${caseName} face sizes`);
    assert.ok(Math.abs(signedVolume - fixture.signed_volume) < 2e-6, `${caseName} signed volume`);
    for (const kind of ["min", "max"] as const)
      for (let axis = 0; axis < 3; axis++)
        assert.ok(Math.abs(bounds(kind)[axis] - fixture.bbox[kind][axis]) < 1e-6, `${caseName} ${kind}[${axis}]`);
    for (const kind of ["abs", "squared"] as const)
      for (let axis = 0; axis < 3; axis++)
        assert.ok(Math.abs(moments[kind][axis] - fixture.position_moments[kind][axis]) < 1e-4, `${caseName} ${kind}[${axis}]`);
  }
  assert.equal(APPROXIMATIONS.get("GeometryNodeVolumeCube") ?? 0, previousCubeCount);
  assert.equal(APPROXIMATIONS.get("GeometryNodeVolumeToMesh") ?? 0, previousMeshCount);
});

